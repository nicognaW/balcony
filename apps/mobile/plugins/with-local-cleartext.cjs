// Lets the app speak plain HTTP (and ws://) to Balcony on the LAN.
//
// Android's network security config can only allow cleartext per exact
// domain or IP, not per IP range, and the Mac's LAN address isn't known when
// the app is built. So the config allows cleartext, trusts only the system's
// CAs, and the app itself refuses any server outside the local network
// (`serverFromAddress` / `pairingFromQr` in @balcony/client). See
// docs/adr/0004-cleartext-only-to-local-addresses.md.
//
// Shaped after T3 Code's withAndroidNetworkSecurityConfig (MIT, (c) 2026 T3
// Tools Inc.).
const fs = require("node:fs");
const path = require("node:path");

const {
  withAndroidManifest,
  withDangerousMod,
} = require("expo/config-plugins");

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-local-cleartext.cjs. The app only connects to
     local network addresses; see docs/adr/0004. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

const withManifest = (config) =>
  withAndroidManifest(config, (next) => {
    const [application] = next.modResults.manifest.application ?? [];

    if (application === undefined) {
      throw new Error("AndroidManifest.xml has no <application> element.");
    }

    application.$["android:networkSecurityConfig"] =
      "@xml/network_security_config";

    return next;
  });

const withResource = (config) =>
  withDangerousMod(config, [
    "android",
    (next) => {
      const dir = path.join(
        next.modRequest.platformProjectRoot,
        "app/src/main/res/xml"
      );

      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(
        path.join(dir, "network_security_config.xml"),
        NETWORK_SECURITY_CONFIG
      );

      return next;
    },
  ]);

module.exports = function withLocalCleartext(config) {
  return withResource(withManifest(config));
};
